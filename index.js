async function displayProjects() {
  const projectElement = document.getElementById("projects");

  const cached = localStorage.getItem(CACHE_KEY);

  if (cached) {
    const parsed = JSON.parse(cached);
    const isFresh = Date.now() - parsed.timestamp < CACHE_TIME;

    if (isFresh) {
      render(parsed.data);
      return;
    }
  }

  const response = await fetch(
    "https://api.github.com/users/jishnukarri/repos"
  );

  if (!response.ok) {
    if (cached) {
      render(JSON.parse(cached).data);
    } else {
      projectElement.innerHTML = "Error loading repos";
    }
    return;
  }

  const data = await response.json();

  localStorage.setItem(CACHE_KEY, JSON.stringify({
    data,
    timestamp: Date.now()
  }));

  render(data);
}
function render(data) {
  const projectElement = document.getElementById("projects");
  projectElement.innerHTML = "";

  const fragment = document.createDocumentFragment();

  data.forEach(repo => {
    const card = document.createElement("div");
    card.className = "group border p-3 min-w-0 overflow-hidden";

    card.innerHTML = `
      <a href="${repo.html_url}">
        <h1 class="font-bold text-base mb-2">${repo.name}</h1>
        <p class="text-[15px]">In ${repo.language ?? "a mysterious set of languages"}</p>
      </a>
    `;

    fragment.appendChild(card);
  });

  projectElement.appendChild(fragment);
}
